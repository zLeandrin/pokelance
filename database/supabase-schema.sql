-- PokéLance — schema inicial para Supabase
-- Execute tudo no SQL Editor do projeto Supabase.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 20),
  balance integer not null default 1000 check (balance >= 0),
  role text not null default 'player' check (role in ('player','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.pokemon (
  id bigint generated by default as identity primary key,
  name text not null,
  pokedex_number integer,
  type text not null default 'Normal',
  emoji text not null default '⭐',
  glow text not null default '#ffcc4d44',
  description text not null default '',
  starting_bid integer not null default 100 check (starting_bid > 0),
  current_bid integer not null default 100 check (current_bid >= 0),
  highest_bidder_id uuid references public.profiles(id),
  highest_bidder_name text,
  winning_bid integer,
  winner_id uuid references public.profiles(id),
  winner_name text,
  status text not null default 'open' check (status in ('open','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bid_history (
  id bigint generated by default as identity primary key,
  pokemon_id bigint not null references public.pokemon(id) on delete cascade,
  bidder_id uuid not null references public.profiles(id),
  bidder_name text not null,
  amount integer not null check (amount > 0),
  total_bid integer not null check (total_bid > 0),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.pokemon enable row level security;
alter table public.bid_history enable row level security;

drop policy if exists "profiles visible to authenticated" on public.profiles;
create policy "profiles visible to authenticated" on public.profiles for select to authenticated using (true);
drop policy if exists "players create own profile" on public.profiles;
create policy "players create own profile" on public.profiles for insert to authenticated with check (id = auth.uid() and role = 'player' and balance = 1000);
drop policy if exists "players update own nickname" on public.profiles;
create policy "players update own nickname" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid() and role = (select p.role from public.profiles p where p.id = auth.uid()));

drop policy if exists "pokemon visible to authenticated" on public.pokemon;
create policy "pokemon visible to authenticated" on public.pokemon for select to authenticated using (true);
drop policy if exists "admins add pokemon" on public.pokemon;
create policy "admins add pokemon" on public.pokemon for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "admins update pokemon" on public.pokemon;
create policy "admins update pokemon" on public.pokemon for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
drop policy if exists "bid history visible to authenticated" on public.bid_history;
create policy "bid history visible to authenticated" on public.bid_history for select to authenticated using (true);

-- Cria automaticamente perfil para cada nova conta, com saldo virtual inicial.
create or replace function public.create_profile_for_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, nickname, balance, role)
  values (new.id, coalesce(nullif(new.raw_user_meta_data->>'nickname',''), split_part(new.email,'@',1)), 1000, 'player')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users
for each row execute procedure public.create_profile_for_user();

-- RPC transacional: valida saldo, leilão aberto e evita corrida entre lances simultâneos.
create or replace function public.place_bid(p_pokemon_id bigint, p_amount integer)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_pokemon public.pokemon%rowtype;
  v_profile public.profiles%rowtype;
  v_total integer;
begin
  if v_user is null then raise exception 'Entre na sua conta para dar um lance.'; end if;
  if p_amount not in (25,50,100) then raise exception 'Valor de lance inválido.'; end if;
  select * into v_pokemon from public.pokemon where id=p_pokemon_id for update;
  if not found then raise exception 'Pokémon não encontrado.'; end if;
  if v_pokemon.status <> 'open' then raise exception 'Este leilão já foi encerrado.'; end if;
  select * into v_profile from public.profiles where id=v_user for update;
  if not found then raise exception 'Perfil do treinador não encontrado.'; end if;
  if v_profile.balance < p_amount then raise exception 'Saldo insuficiente.'; end if;
  v_total := v_pokemon.current_bid + p_amount;
  update public.profiles set balance=balance-p_amount where id=v_user;
  update public.pokemon set current_bid=v_total, highest_bidder_id=v_user, highest_bidder_name=v_profile.nickname, updated_at=now() where id=p_pokemon_id;
  insert into public.bid_history(pokemon_id,bidder_id,bidder_name,amount,total_bid)
  values(p_pokemon_id,v_user,v_profile.nickname,p_amount,v_total);
  return jsonb_build_object('message','Lance de '||p_amount||' registrado! Novo total: '||v_total);
end;
$$;

create or replace function public.close_auction(p_pokemon_id bigint)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_pokemon public.pokemon%rowtype;
begin
  if v_user is null or not exists(select 1 from public.profiles where id=v_user and role='admin') then
    raise exception 'Somente o administrador pode encerrar leilões.';
  end if;
  select * into v_pokemon from public.pokemon where id=p_pokemon_id for update;
  if not found then raise exception 'Pokémon não encontrado.'; end if;
  if v_pokemon.status <> 'open' then raise exception 'Este leilão já foi encerrado.'; end if;
  update public.pokemon set status='closed', winner_id=highest_bidder_id, winner_name=highest_bidder_name, winning_bid=case when highest_bidder_id is null then current_bid else current_bid end, updated_at=now() where id=p_pokemon_id;
  return jsonb_build_object('message','Leilão de '||v_pokemon.name||' encerrado.');
end;
$$;

revoke all on function public.place_bid(bigint,integer) from public;
grant execute on function public.place_bid(bigint,integer) to authenticated;
revoke all on function public.close_auction(bigint) from public;
grant execute on function public.close_auction(bigint) to authenticated;

